create table if not exists circle_chat_messages (
    id bigint generated by default as identity primary key,
    circle_id bigint not null references book_circles(id),
    sender_user_id bigint not null references users(id),
    content varchar(2000) not null,
    created_at timestamp not null,
    deleted_at timestamp,
    deleted_by_user_id bigint references users(id)
);

create index if not exists idx_circle_chat_messages_circle_id_id_desc
    on circle_chat_messages(circle_id, id desc);
