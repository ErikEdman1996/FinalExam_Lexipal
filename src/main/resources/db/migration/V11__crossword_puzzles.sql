create table if not exists crossword_puzzles (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    challenge_id bigint not null references challenges(id),
    status varchar(20) not null,
    created_at timestamp not null,
    submitted_at timestamp,
    public_puzzle jsonb not null,
    solution jsonb not null,
    word_sources jsonb not null
);

create index if not exists idx_crossword_puzzles_user_created
    on crossword_puzzles(user_id, created_at);

alter table challenge_attempts
    alter column word_lookup_id drop not null;

alter table challenge_attempts
    add column if not exists crossword_puzzle_id bigint;

alter table challenge_attempts
    add constraint fk_challenge_attempt_crossword_puzzle
        foreign key (crossword_puzzle_id) references crossword_puzzles(id);

create unique index if not exists uk_challenge_attempts_crossword_puzzle
    on challenge_attempts(crossword_puzzle_id)
    where crossword_puzzle_id is not null;
