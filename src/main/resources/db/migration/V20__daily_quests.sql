create table if not exists daily_quests (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    quest_date date not null,
    type varchar(40) not null,
    target_value integer not null,
    progress_value integer not null default 0,
    status varchar(40) not null,
    xp_reward integer not null,
    coin_reward integer not null,
    baseline_value integer,
    source_session_id bigint references sessions(id),
    created_at timestamp not null,
    completed_at timestamp,
    constraint uk_daily_quests_user_date unique (user_id, quest_date)
);

create index if not exists idx_daily_quests_user_date
    on daily_quests(user_id, quest_date);

create index if not exists idx_daily_quests_source_session
    on daily_quests(source_session_id);
