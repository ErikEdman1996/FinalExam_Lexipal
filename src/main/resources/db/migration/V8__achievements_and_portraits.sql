create table if not exists achievement_definitions (
    id bigint generated by default as identity primary key,
    code varchar(80) not null unique,
    category varchar(50) not null,
    title varchar(120) not null,
    description varchar(255) not null,
    metric_key varchar(80) not null,
    threshold integer not null,
    sort_order integer not null,
    active boolean not null default true
);

create table if not exists user_achievements (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    achievement_id bigint not null references achievement_definitions(id),
    unlocked_at timestamp not null,
    progress_value_at_unlock integer not null,
    constraint uk_user_achievements_user_definition unique (user_id, achievement_id)
);

create index if not exists idx_user_achievements_user on user_achievements(user_id);

create table if not exists portrait_definitions (
    id bigint generated by default as identity primary key,
    code varchar(80) not null unique,
    name varchar(120) not null,
    description varchar(255) not null,
    asset_key varchar(120) not null,
    required_level integer not null,
    sort_order integer not null,
    active boolean not null default true
);

create table if not exists user_portrait_unlocks (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    portrait_id bigint not null references portrait_definitions(id),
    unlocked_at timestamp not null,
    constraint uk_user_portrait_unlocks_user_portrait unique (user_id, portrait_id)
);

create index if not exists idx_user_portrait_unlocks_user on user_portrait_unlocks(user_id);

alter table users
    add column if not exists selected_portrait_id bigint references portrait_definitions(id);
