create table if not exists catalog_books (
    id bigint generated by default as identity primary key,
    title varchar(200) not null,
    author varchar(200) not null,
    title_normalized varchar(200) not null,
    author_normalized varchar(200) not null,
    created_at timestamp not null,
    constraint uk_catalog_books unique (title_normalized, author_normalized)
);

create index if not exists idx_catalog_books_normalized on catalog_books(title_normalized, author_normalized);

create table if not exists reading_lists (
    id bigint generated by default as identity primary key,
    title varchar(120) not null,
    description varchar(2000),
    owner_user_id bigint not null references users(id),
    status varchar(20) not null,
    star_count integer not null default 0,
    created_at timestamp not null,
    updated_at timestamp not null
);

create index if not exists idx_reading_lists_status_stars on reading_lists(status, star_count desc);
create index if not exists idx_reading_lists_owner on reading_lists(owner_user_id);

create table if not exists reading_list_books (
    id bigint generated by default as identity primary key,
    list_id bigint not null references reading_lists(id) on delete cascade,
    catalog_book_id bigint not null references catalog_books(id),
    position integer not null,
    note varchar(500),
    constraint uk_reading_list_books_position unique (list_id, position),
    constraint uk_reading_list_books_catalog unique (list_id, catalog_book_id)
);

create index if not exists idx_reading_list_books_list on reading_list_books(list_id);
create index if not exists idx_reading_list_books_catalog on reading_list_books(catalog_book_id);

create table if not exists reading_list_subscriptions (
    id bigint generated by default as identity primary key,
    list_id bigint not null references reading_lists(id) on delete cascade,
    user_id bigint not null references users(id),
    subscribed_at timestamp not null,
    completed_at timestamp,
    constraint uk_reading_list_subscriptions unique (list_id, user_id)
);

create index if not exists idx_reading_list_subscriptions_user on reading_list_subscriptions(user_id);

create table if not exists reading_list_stars (
    id bigint generated by default as identity primary key,
    list_id bigint not null references reading_lists(id) on delete cascade,
    user_id bigint not null references users(id),
    starred_at timestamp not null,
    constraint uk_reading_list_stars unique (list_id, user_id)
);

create index if not exists idx_reading_list_stars_user on reading_list_stars(user_id);

alter table daily_activities add column if not exists external_ref_id bigint;
create index if not exists idx_daily_activities_user_type_ref on daily_activities(user_id, activity_type, external_ref_id);
