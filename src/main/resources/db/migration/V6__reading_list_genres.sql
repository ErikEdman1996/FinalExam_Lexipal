create table if not exists reading_list_genres (
    id bigint generated by default as identity primary key,
    list_id bigint not null references reading_lists(id) on delete cascade,
    genre varchar(50) not null,
    genre_normalized varchar(50) not null,
    constraint uk_reading_list_genres unique (list_id, genre_normalized)
);

create index if not exists idx_reading_list_genres_list on reading_list_genres(list_id);
create index if not exists idx_reading_list_genres_normalized on reading_list_genres(genre_normalized);
