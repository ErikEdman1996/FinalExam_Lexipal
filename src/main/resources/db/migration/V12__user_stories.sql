alter table users add column if not exists adult_content_enabled boolean not null default false;

create table if not exists stories (
    id bigint generated by default as identity primary key,
    title varchar(180) not null,
    summary varchar(2000),
    owner_user_id bigint not null references users(id),
    status varchar(20) not null,
    attribution varchar(20) not null,
    is_adult boolean not null default false,
    like_count integer not null default 0,
    total_view_count bigint not null default 0,
    unique_view_count bigint not null default 0,
    published_at timestamp,
    latest_chapter_published_at timestamp,
    created_at timestamp not null,
    updated_at timestamp not null
);

create index if not exists idx_stories_status_adult_likes on stories(status, is_adult, like_count desc);
create index if not exists idx_stories_status_adult_views on stories(status, is_adult, total_view_count desc);
create index if not exists idx_stories_status_adult_published on stories(status, is_adult, published_at desc);
create index if not exists idx_stories_latest_chapter on stories(latest_chapter_published_at desc);
create index if not exists idx_stories_owner on stories(owner_user_id);

create table if not exists story_chapters (
    id bigint generated by default as identity primary key,
    story_id bigint not null references stories(id) on delete cascade,
    position integer not null,
    title varchar(180) not null,
    body_markdown text not null,
    status varchar(20) not null,
    published_at timestamp,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint uk_story_chapters_position unique (story_id, position)
);

create index if not exists idx_story_chapters_story_status on story_chapters(story_id, status);
create index if not exists idx_story_chapters_story_position on story_chapters(story_id, position);

create table if not exists story_genres (
    id bigint generated by default as identity primary key,
    story_id bigint not null references stories(id) on delete cascade,
    genre varchar(50) not null,
    genre_normalized varchar(50) not null,
    constraint uk_story_genres unique (story_id, genre_normalized)
);

create index if not exists idx_story_genres_story on story_genres(story_id);
create index if not exists idx_story_genres_normalized on story_genres(genre_normalized);

create table if not exists story_tags (
    id bigint generated by default as identity primary key,
    story_id bigint not null references stories(id) on delete cascade,
    tag varchar(50) not null,
    tag_normalized varchar(50) not null,
    constraint uk_story_tags unique (story_id, tag_normalized)
);

create index if not exists idx_story_tags_story on story_tags(story_id);
create index if not exists idx_story_tags_normalized on story_tags(tag_normalized);

create table if not exists story_likes (
    id bigint generated by default as identity primary key,
    story_id bigint not null references stories(id) on delete cascade,
    user_id bigint not null references users(id),
    liked_at timestamp not null,
    constraint uk_story_likes unique (story_id, user_id)
);

create index if not exists idx_story_likes_user on story_likes(user_id);

create table if not exists story_subscriptions (
    id bigint generated by default as identity primary key,
    story_id bigint not null references stories(id) on delete cascade,
    user_id bigint not null references users(id),
    subscribed_at timestamp not null,
    constraint uk_story_subscriptions unique (story_id, user_id)
);

create index if not exists idx_story_subscriptions_user on story_subscriptions(user_id);

create table if not exists story_chapter_views (
    id bigint generated by default as identity primary key,
    story_id bigint not null references stories(id) on delete cascade,
    chapter_id bigint not null references story_chapters(id) on delete cascade,
    user_id bigint not null references users(id),
    viewed_at timestamp not null
);

create index if not exists idx_story_chapter_views_story on story_chapter_views(story_id);
create index if not exists idx_story_chapter_views_chapter on story_chapter_views(chapter_id);
create index if not exists idx_story_chapter_views_user on story_chapter_views(user_id);

create table if not exists story_unique_views (
    id bigint generated by default as identity primary key,
    story_id bigint not null references stories(id) on delete cascade,
    user_id bigint not null references users(id),
    first_viewed_at timestamp not null,
    constraint uk_story_unique_views unique (story_id, user_id)
);

create index if not exists idx_story_unique_views_user on story_unique_views(user_id);
