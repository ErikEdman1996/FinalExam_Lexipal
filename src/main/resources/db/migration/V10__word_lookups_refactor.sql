create table if not exists word_lookups (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    word_id bigint not null references words(id),
    first_looked_up_at timestamp not null,
    last_looked_up_at timestamp not null,
    lookup_count integer not null,
    first_source_session_id bigint,
    last_source_session_id bigint,
    constraint uk_word_lookup_user_word unique (user_id, word_id)
);

create index if not exists idx_word_lookups_user_last_lookup
    on word_lookups(user_id, last_looked_up_at);

create index if not exists idx_word_lookups_user_word
    on word_lookups(user_id, word_id);

