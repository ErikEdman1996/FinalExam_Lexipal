create table if not exists note_tags (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    name varchar(50) not null,
    name_normalized varchar(50) not null,
    color_hex varchar(7),
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint uk_note_tags_user_name unique (user_id, name_normalized)
);

create index if not exists idx_note_tags_user on note_tags(user_id);
create index if not exists idx_note_tags_user_normalized on note_tags(user_id, name_normalized);

create table if not exists note_tag_assignments (
    id bigint generated by default as identity primary key,
    note_id bigint not null references notes(id) on delete cascade,
    tag_id bigint not null references note_tags(id) on delete cascade,
    assigned_at timestamp not null,
    constraint uk_note_tag_assignments unique (note_id, tag_id)
);

create index if not exists idx_note_tag_assignments_note on note_tag_assignments(note_id);
create index if not exists idx_note_tag_assignments_tag on note_tag_assignments(tag_id);
