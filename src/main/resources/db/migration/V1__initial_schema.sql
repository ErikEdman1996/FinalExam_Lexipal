create table if not exists users (
    id bigint generated by default as identity primary key,
    keycloak_sub varchar(255) not null unique,
    nickname varchar(20),
    nickname_normalized varchar(20) unique,
    created_at timestamp,
    status varchar(20) not null,
    total_pages_read integer,
    total_books_read integer,
    total_xp integer
);

create table if not exists challenges (
    id bigint generated by default as identity primary key,
    type varchar(50) not null unique,
    description varchar(255) not null,
    difficulty varchar(50) not null
);

create table if not exists words (
    id bigint generated by default as identity primary key,
    lemma varchar(255) not null unique,
    rarity_score double precision,
    source varchar(100),
    definitions jsonb,
    phonetics jsonb
);

create table if not exists books (
    id bigint generated by default as identity primary key,
    title varchar(100) not null,
    author varchar(100) not null,
    read_pages integer,
    total_pages integer not null,
    created_at timestamp not null,
    status varchar(20) not null,
    user_id bigint references users(id)
);

create table if not exists book_circles (
    id bigint generated by default as identity primary key,
    invite_code varchar(6) not null unique,
    book_title varchar(100) not null,
    book_author varchar(100) not null,
    total_pages integer not null,
    member_cap integer not null,
    visibility varchar(32) not null,
    status varchar(32) not null,
    owner_user_id bigint not null references users(id),
    created_at timestamp not null
);

create index if not exists idx_book_circles_invite_code on book_circles(invite_code);

create table if not exists sessions (
    id bigint generated by default as identity primary key,
    duration_seconds bigint,
    start_page integer not null,
    end_page integer,
    pages_read integer not null,
    reflection text,
    status varchar(20) not null,
    session_date timestamp not null,
    completed_at timestamp,
    user_id bigint not null references users(id),
    book_id bigint not null references books(id),
    captured_word_count integer not null
);

create table if not exists notes (
    id bigint generated by default as identity primary key,
    quoted_text text not null,
    page_number integer not null,
    chapter_label varchar(100),
    created_at timestamp not null,
    user_id bigint not null references users(id),
    book_id bigint not null references books(id),
    source_session_id bigint
);

create table if not exists codex_entries (
    id bigint generated by default as identity primary key,
    word_id bigint not null references words(id),
    specific_definition varchar(255),
    xp_value integer,
    created_at timestamp,
    source_session_id bigint,
    user_id bigint not null references users(id),
    constraint uk_codex_entry_user_word unique (user_id, word_id)
);

create table if not exists challenge_attempts (
    id bigint generated by default as identity primary key,
    user_answer varchar(1000),
    result varchar(20) not null,
    xp_awarded integer not null,
    attempted_at timestamp not null,
    user_id bigint not null references users(id),
    challenge_id bigint not null references challenges(id),
    codex_entry_id bigint references codex_entries(id),
    word_id bigint references words(id)
);

create table if not exists daily_activities (
    id bigint generated by default as identity primary key,
    activity_date date not null,
    activity_type varchar(32) not null,
    xp_earned integer not null,
    user_id bigint not null references users(id),
    session_id bigint references sessions(id)
);

create table if not exists streak_metadata (
    id bigint generated by default as identity primary key,
    current_streak integer not null,
    longest_streak integer not null,
    last_activity_date date,
    user_id bigint not null,
    constraint uk_streak_metadata_user unique (user_id),
    constraint fk_streak_metadata_user foreign key (user_id) references users(id)
);

create table if not exists circle_members (
    id bigint generated by default as identity primary key,
    circle_id bigint not null references book_circles(id),
    user_id bigint not null references users(id),
    book_id bigint not null references books(id),
    role varchar(20) not null,
    joined_at timestamp not null,
    constraint uk_circle_members_circle_user unique (circle_id, user_id)
);

create table if not exists circle_member_blocks (
    id bigint generated by default as identity primary key,
    circle_id bigint not null references book_circles(id),
    user_id bigint not null references users(id),
    blocked_by_user_id bigint not null references users(id),
    blocked_at timestamp not null,
    constraint uk_circle_member_blocks_circle_user unique (circle_id, user_id)
);
