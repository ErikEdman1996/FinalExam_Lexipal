create table if not exists store_item_definitions (
    id bigint generated by default as identity primary key,
    code varchar(80) not null unique,
    name varchar(120) not null,
    description varchar(255) not null,
    item_type varchar(40) not null,
    price_coins integer not null,
    sort_order integer not null,
    active boolean not null default true
);

create table if not exists theme_definitions (
    id bigint generated by default as identity primary key,
    code varchar(80) not null unique,
    name varchar(120) not null,
    description varchar(255) not null,
    tone varchar(20) not null,
    sort_order integer not null,
    active boolean not null default true,
    store_item_id bigint unique references store_item_definitions(id)
);

create table if not exists user_theme_unlocks (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    theme_id bigint not null references theme_definitions(id),
    unlocked_at timestamp not null,
    constraint uk_user_theme_unlocks_user_theme unique (user_id, theme_id)
);

create index if not exists idx_user_theme_unlocks_user on user_theme_unlocks(user_id);

alter table users
    add column if not exists selected_theme_id bigint references theme_definitions(id);
