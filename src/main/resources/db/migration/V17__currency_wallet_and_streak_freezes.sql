alter table users
    add column if not exists coin_balance integer not null default 0;

alter table streak_metadata
    add column if not exists available_streak_freezes integer not null default 0;

alter table streak_metadata
    add column if not exists freeze_protected_through_date date;

create table if not exists currency_transactions (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id),
    type varchar(20) not null,
    reason varchar(80) not null,
    amount integer not null,
    balance_after integer not null,
    source_type varchar(80),
    source_reference_id bigint,
    created_at timestamp not null
);

create index if not exists idx_currency_transactions_user_created
    on currency_transactions(user_id, created_at, id);
